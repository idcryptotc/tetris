    // Индекс глифа по символу (-1, если не латинская буква).
    inline int GlyphIndex(char c)
    {
        if (c >= 'a' && c <= 'z')
        {
            c = static_cast<char>(c - 'a' + 'A');
        }

        if (c < 'A' || c > 'Z')
        {
            return -1;
        }

        return c - 'A';
    }
